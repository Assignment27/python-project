# Assignment operators are used to assign value to variables.

# 1. '='
x = 5
print(x)

# re-assigning
x = 10
print(x)

name = "larry"
print(name)

name = "ola"
print(name)

# 2. '+='

x += 7 # same as x = x + 7
print(x)

x +=3
print(x)

# 3. '-='

x -=2 # same as x = x -2
print(x)

# 4. '*='
x *= 3
print(x)

#  5. '/='
x /= 2
print(x)

# 6. '%='
x %= 3
print(x)

# 7. '**='
x **= 3
print(x)



